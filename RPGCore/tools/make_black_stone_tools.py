out = sys.argv[1] if len(sys.argv) > 1 else "."
row = Image.new("RGBA", (len(TOOLS)*16*10 + (len(TOOLS)-1)*20, 160), (200,200,200,255))
for i,(name, art) in enumerate(TOOLS.items()):
    lines = [l for l in art.strip("\n").split("\n")]
    assert len(lines) == 16 and all(len(l) == 16 for l in lines), (name, [len(l) for l in lines])
    img = Image.new("RGBA", (16,16), (0,0,0,0))
    for y,l in enumerate(lines):
        for x,c in enumerate(l):
            if c in PAL: img.putpixel((x,y), PAL[c] + (255,))
    img.save(os.path.join(out, name + ".png"))
    big = img.resize((160,160), Image.NEAREST)
    row.paste(big, (i*180, 0), big)
row.save(os.path.join(out, "_tools_preview.png"))
